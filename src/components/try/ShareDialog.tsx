// Share-conversation dialog (ported from the Franklin Desktop app, adapted to
// the web message model). Pick which messages to include, then copy a public
// link, copy them as text, or export a clean image. The link uploads the
// selected snapshot to /api/share (same-origin) and copies the returned
// /s/<id> URL. Tool activity (search queries + tools used) is derived from each
// assistant message's `activity` field and travels with the share so the public
// page reproduces the tool usage too.

import { useMemo, useRef, useState } from "react";
import { toPng } from "html-to-image";
import { Check, Copy, ImageDown, Link2, X } from "lucide-react";
import type { ChatMessage } from "@/hooks/use-franklin-chat";
import { MessageContent } from "./MessageContent";
import { useTryLang } from "@/lib/try-i18n";

// Image-share message cap (Doubao-style). A very tall PNG hits browser canvas
// size limits and degrades; over this many selected bubbles we disable "share
// image" (the link has no such limit, so it stays available).
const IMAGE_SHARE_LIMIT = 30;

// Where the public share snapshot is published. Same-origin on the web.
const SHARE_API = "/api/share";

interface ToolStep {
  label: string;
  detail?: string;
}

